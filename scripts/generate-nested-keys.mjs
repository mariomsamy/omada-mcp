#!/usr/bin/env node
/**
 * Generate src/utils/openapiNestedKeys.ts: nested request-body key allowlists taken from the bundled
 * Omada Open API spec (docs/openapi/00-all.json). Run after updating the spec, then `npm run lint:fix`.
 *
 *   node scripts/generate-nested-keys.mjs
 *
 * Only nested objects are emitted (the top-level keys live in OPENAPI_BODY_KEYS). Map-typed objects
 * (additionalProperties) have no fixed key set and are left free-form, bounded by the payload caps.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'docs/openapi/00-all.json'), 'utf8'));
const schemas = spec.components.schemas;

const V1 = '/openapi/v1/{omadacId}/sites/{siteId}';
const SSID = `${V1}/wireless-network/wlans/{wlanId}/ssids/{ssidId}`;
/** Body name (matches OPENAPI_BODY_KEYS) -> [method, path] of the operation whose request body it is. */
const OPERATIONS = {
    createSsid: ['post', `${V1}/wireless-network/wlans/{wlanId}/ssids`],
    lanNetwork: ['post', '/openapi/v2/{omadacId}/sites/{siteId}/lan-networks'],
    lanProfile: ['post', `${V1}/lan-profiles`],
    portForwarding: ['post', `${V1}/nat/port-forwardings`],
    staticRouting: ['post', `${V1}/routing/static-routings`],
    internetPort: ['patch', `${V1}/wan/networks/port-setting`],
    ssidHotspotV2: ['patch', `${SSID}/update-hotspotv2`],
    ssidMacFilter: ['patch', `${SSID}/update-mac-filter`],
    ssidMultiCast: ['patch', `${SSID}/update-multicast-config`],
    ssidRateControl: ['patch', `${SSID}/update-rate-control`],
    ssidRateLimit: ['patch', `${SSID}/update-rate-limit`],
    ssidWlanSchedule: ['patch', `${SSID}/update-wlan-schedule`],
    rfPlanningConfig: ['put', `${V1}/rfPlanning/config`],
};

function resolve(schema, seen = new Set()) {
    if (!schema || typeof schema !== 'object') return {};
    if (schema.$ref) {
        const name = schema.$ref.split('/').pop();
        if (seen.has(name)) return {};
        return resolve(schemas[name], new Set([...seen, name]));
    }
    if (schema.allOf) {
        const properties = {};
        for (const part of schema.allOf) Object.assign(properties, resolve(part, seen).properties ?? {});
        return { type: 'object', properties };
    }
    return schema;
}

/** Returns a NestedKeySpec-like object for an object schema, or undefined when it has no fixed keys. */
function specFor(schema, depth) {
    let resolved = resolve(schema);
    while (resolved.type === 'array' && resolved.items) resolved = resolve(resolved.items);
    const properties = resolved.properties;
    if (!properties || Object.keys(properties).length === 0 || depth > 6) return undefined;
    const children = {};
    for (const [key, value] of Object.entries(properties)) {
        const child = specFor(value, depth + 1);
        if (child) children[key] = child;
    }
    return { keys: Object.keys(properties).sort(), ...(Object.keys(children).length > 0 ? { children } : {}) };
}

const output = {};
for (const [name, [method, path]] of Object.entries(OPERATIONS)) {
    const operation = spec.paths[path]?.[method];
    if (!operation) throw new Error(`Operation not found in spec: ${method.toUpperCase()} ${path}`);
    const content = operation.requestBody?.content ?? {};
    const body = specFor(Object.values(content)[0]?.schema, 0);
    if (body?.children) output[name] = body.children;
}

const header = `// Generated by scripts/generate-nested-keys.mjs from docs/openapi/00-all.json. Do not edit by hand.

/** Allowed keys of one nested request-body object; \`children\` describe its nested objects (array items included). */
export interface NestedKeySpec {
    readonly keys: readonly string[];
    readonly children?: Readonly<Record<string, NestedKeySpec>>;
}

/** Nested request-body key allowlists per body (top-level keys are in OPENAPI_BODY_KEYS). */
export const OPENAPI_NESTED_KEYS: Readonly<Record<string, Readonly<Record<string, NestedKeySpec>>>> = `;
writeFileSync(join(root, 'src/utils/openapiNestedKeys.ts'), `${header}${JSON.stringify(output, null, 4)};\n`);
console.log(`Wrote nested allowlists for: ${Object.keys(output).join(', ')}`);
